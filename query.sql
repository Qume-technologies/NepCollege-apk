-- ----------------------------------------------------------------------------
-- 2. TABLE DEFINITIONS
-- ----------------------------------------------------------------------------

-- Table: profiles
CREATE TABLE IF NOT EXISTS public.profiles (
    student_id VARCHAR(50) PRIMARY KEY,
    full_name TEXT NOT NULL,
    department TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    password TEXT NOT NULL,
    admission_year INTEGER,
    room_no VARCHAR(20),
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: attendance
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(50) NOT NULL REFERENCES public.profiles(student_id) ON DELETE CASCADE,
    month_name VARCHAR(20) NOT NULL,
    present_days INTEGER DEFAULT 0,
    total_days INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: timetable
CREATE TABLE IF NOT EXISTS public.timetable (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department TEXT NOT NULL,
    admission_year INTEGER NOT NULL,
    room_number VARCHAR(20),
    day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7), -- 1=Sun, 2=Mon... 7=Sat
    time_start VARCHAR(20) NOT NULL,
    time_end VARCHAR(20) NOT NULL,
    subject_name TEXT NOT NULL,
    teacher_name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: assignments
CREATE TABLE IF NOT EXISTS public.assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department TEXT,
    admission_year INTEGER,
    room_no VARCHAR(20),
    title TEXT NOT NULL,
    subject TEXT NOT NULL,
    description TEXT,
    due_date TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: notices
CREATE TABLE IF NOT EXISTS public.notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    department TEXT, -- NULL applies to all departments
    room_no VARCHAR(20), -- NULL applies to all rooms
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: notifications
CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(50), -- NULL applies to all students
    department TEXT,
    room_no VARCHAR(20),
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: fees
CREATE TABLE IF NOT EXISTS public.fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(50) NOT NULL REFERENCES public.profiles(student_id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    due_date VARCHAR(30),
    is_paid BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: exams
CREATE TABLE IF NOT EXISTS public.exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department TEXT,
    title TEXT NOT NULL,
    exam_type VARCHAR(50) DEFAULT 'Term Exam',
    start_date VARCHAR(30) NOT NULL,
    end_date VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: results
CREATE TABLE IF NOT EXISTS public.results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(50) NOT NULL REFERENCES public.profiles(student_id) ON DELETE CASCADE,
    exam_id VARCHAR(50),
    exam_title TEXT,
    subject_name TEXT NOT NULL,
    gpa NUMERIC(3, 2),
    grade VARCHAR(5),
    status VARCHAR(20) DEFAULT 'Pass',
    url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: leave_notes
CREATE TABLE IF NOT EXISTS public.leave_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(50) NOT NULL REFERENCES public.profiles(student_id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    description TEXT NOT NULL,
    start_date VARCHAR(30) NOT NULL,
    end_date VARCHAR(30),
    status VARCHAR(20) DEFAULT 'Pending', -- Pending, Accepted, Rejected
    admin_reply TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 3. INDEXES FOR HIGH-PERFORMANCE QUERIES
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);
CREATE INDEX IF NOT EXISTS idx_attendance_student_id ON public.attendance(student_id);
CREATE INDEX IF NOT EXISTS idx_timetable_dept_year ON public.timetable(department, admission_year);
CREATE INDEX IF NOT EXISTS idx_assignments_due_date ON public.assignments(due_date);
CREATE INDEX IF NOT EXISTS idx_notices_created_at ON public.notices(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_student ON public.notifications(student_id);
CREATE INDEX IF NOT EXISTS idx_fees_student ON public.fees(student_id);
CREATE INDEX IF NOT EXISTS idx_results_student_exam ON public.results(student_id, exam_id);
CREATE INDEX IF NOT EXISTS idx_leave_notes_student ON public.leave_notes(student_id);

-- ----------------------------------------------------------------------------
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- ----------------------------------------------------------------------------
-- Enabling RLS with public access policies since the app handles direct table queries
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.timetable ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exams ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.results ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leave_notes ENABLE ROW LEVEL SECURITY;

-- Allow anon/public full select and write access (direct query model)
CREATE POLICY "Allow public select profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Allow public insert profiles" ON public.profiles FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update profiles" ON public.profiles FOR UPDATE USING (true);

CREATE POLICY "Allow public select attendance" ON public.attendance FOR SELECT USING (true);
CREATE POLICY "Allow public select timetable" ON public.timetable FOR SELECT USING (true);
CREATE POLICY "Allow public select assignments" ON public.assignments FOR SELECT USING (true);
CREATE POLICY "Allow public select notices" ON public.notices FOR SELECT USING (true);
CREATE POLICY "Allow public select notifications" ON public.notifications FOR SELECT USING (true);
CREATE POLICY "Allow public select fees" ON public.fees FOR SELECT USING (true);
CREATE POLICY "Allow public select exams" ON public.exams FOR SELECT USING (true);
CREATE POLICY "Allow public select results" ON public.results FOR SELECT USING (true);

CREATE POLICY "Allow public select leave_notes" ON public.leave_notes FOR SELECT USING (true);
CREATE POLICY "Allow public insert leave_notes" ON public.leave_notes FOR INSERT WITH CHECK (true);

